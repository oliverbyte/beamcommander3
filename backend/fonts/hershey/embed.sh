#!/usr/bin/env bash
# Regenerates backend/hershey_font_data.h: every *.jhf in this folder
# embedded byte for byte as a raw string literal (each file is < 16 KB, the
# MSVC limit for one literal). backend/tests/test_laser_text.cpp checks the
# embedded text still equals the files. Run from anywhere:
#   bash backend/fonts/hershey/embed.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/../../hershey_font_data.h"
{
  echo '#pragma once'
  echo '// GENERATED by backend/fonts/hershey/embed.sh - do not edit. The Hershey fonts'
  echo '// in backend/fonts/hershey/ (see LICENSE-HERSHEY.txt there): The Hershey Fonts'
  echo '// were originally created by Dr. A. V. Hershey while working at the U. S.'
  echo '// National Bureau of Standards. The format of the Font data in this'
  echo '// distribution was originally created by James Hurt, Cognition, Inc.'
  for f in "$HERE"/*.jhf; do
    name="$(basename "$f" .jhf)"
    printf 'static const char HERSHEY_%s[] = R"JHF(' "$name"
    cat "$f"
    printf ')JHF";\n'
  done
} > "$OUT"
echo "wrote $OUT"
